"""Summarize results/e2e/qwen3_8b_fp8.json into results/e2e/summary.md. No GPU needed."""

import json
import os
import statistics

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, "results", "e2e", "qwen3_8b_fp8.json")
PPL = os.path.join(REPO, "results", "e2e", "wikitext2_ppl.json")


def iqr(xs):
    if len(xs) < 2:
        return xs[0], xs[0]
    q = statistics.quantiles(xs, n=4, method="inclusive")
    return q[0], q[2]


def fmt(xs, nd):
    lo, hi = iqr(xs)
    return f"{statistics.median(xs):.{nd}f} [{lo:.{nd}f}-{hi:.{nd}f}]"


def compare(run, ref):
    """Greedy-token agreement and logprob differences of run vs ref."""
    g, rg = run["outputs"]["greedy"], ref["outputs"]["greedy"]
    exact, prefix, total, pos_match, pos_total, lp_greedy = 0, 0, 0, 0, 0, 0.0
    for a, b in zip(g, rg):
        ta, tb = a["tokens"], b["tokens"]
        n = 0
        while n < min(len(ta), len(tb)) and ta[n] == tb[n]:
            n += 1
        exact += ta == tb
        prefix += n
        total += len(tb)
        pos_match += sum(x == y for x, y in zip(ta, tb))
        pos_total += max(len(ta), len(tb))
        # Same context up to and including the first divergent position.
        for i in range(min(n + 1, len(ta), len(tb))):
            lp_greedy = max(lp_greedy, abs(a["logprobs"][i] - b["logprobs"][i]))
    tf, rtf = run["outputs"]["teacher_forced"], ref["outputs"]["teacher_forced"]
    diffs = [abs(x - y) for a, b in zip(tf, rtf) for x, y in zip(a, b)]
    return {"prompts": len(rg), "identical": exact, "prefix_tokens": prefix, "ref_tokens": total,
            "pos_match": pos_match, "pos_total": pos_total, "lp_greedy_max": lp_greedy,
            "lp_forced_max": max(diffs), "lp_forced_mean": statistics.fmean(diffs),
            "lp_forced_p99": statistics.quantiles(diffs, n=100, method="inclusive")[98],
            "lp_forced_n": len(diffs)}


def ppl_section():
    if not os.path.exists(PPL):
        return []
    with open(PPL) as f:
        p = json.load(f)
    r0 = p["runs"][0]
    ds = r0["dataset"]
    out = ["\n## wikitext-2 perplexity\n",
           f"Source: results/e2e/wikitext2_ppl.json (bench/e2e_vllm.py --ppl), commit "
           f"{r0['git']['commit'][:10]}{' (dirty)' if r0['git']['dirty'] else ''}. "
           f"{ds['config']} {ds['split']} ({ds['rows']} rows, {ds['file']}, sha256 "
           f"{ds['sha256'][:12]}...), joined with blank lines: {r0['tokens']} tokens, "
           f"{r0['windows']} non-overlapping windows of {r0['window']}, each scored on its own "
           f"(prompt_logprobs; {r0['scored_tokens']} scored tokens). Engine: "
           f"{json.dumps(r0['engine'])}.\n",
           "| run | kernel (vLLM's log) | perplexity | mean NLL |", "|---|---|---|---|"]
    for r in p["runs"]:
        out.append(f"| {r['config']} ({r['tag']}) | {', '.join(r.get('selected_from_log', [])) or '?'}"
                   f" | {r['ppl']:.4f} | {r['nll']:.5f} |")
    out += ["\nPer-token logprob differences over the same scored tokens:\n",
            "| run | vs | mean abs | p99 abs | p99.9 abs | max abs | mean signed | identical |",
            "|---|---|---|---|---|---|---|---|"]
    for d in p["logprob_diffs"]:
        out.append(f"| {d['run']} | {d['vs']} | {d['mean_abs']:.2e} | {d['p99_abs']:.2e} | "
                   f"{d['p999_abs']:.2e} | {d['max_abs']:.3f} | {d['mean_signed']:+.2e} | "
                   f"{100 * d['identical'] / d['tokens']:.1f}% |")
    return out


def main():
    with open(SRC) as f:
        d = json.load(f)
    runs = d["runs"]
    by = {c: [r for r in runs if r["config"] == c] for c in ("stock", "plugin")}
    ref = next(r for r in by["stock"] if r["outputs"]["reference"] == "self")
    out = ["# End-to-end results (generated by bench/report_e2e.py)", ""]
    r0 = runs[0]
    out.append(f"Source: results/e2e/qwen3_8b_fp8.json, {len(by['stock'])} stock and "
               f"{len(by['plugin'])} plugin runs (interleaved, one process each, GPU lock per run), "
               f"model {r0['model']}, vLLM {r0['vllm']}, torch {r0['torch']}, commit "
               f"{r0['git']['commit'][:10]}{' (dirty)' if r0['git']['dirty'] else ''}.")
    out.append(f"Engine: {json.dumps(r0['engine'])}.")
    for c in ("stock", "plugin"):
        sel = sorted({k for r in by[c] for k in r.get("selected_from_log", [])})
        out.append(f"{c}: VLLM_PLUGINS={by[c][0]['vllm_plugins']}; block-FP8 linear kernel "
                   f"selected (vLLM's log, every run): {', '.join(sel) or '?'}.")
    clocks = [float(s["clocks.sm"].split()[0]) for r in runs for s in r["gpu_samples"]
              if s.get("clocks.sm") and s["clocks.sm"].split()[0].isdigit()]
    if clocks:
        out.append(f"SM clock (nvidia-smi, 1 s samples over all runs, idle phases included): median "
                   f"{statistics.median(clocks):.0f} MHz, min {min(clocks):.0f}, max {max(clocks):.0f}.")
    out.append("")
    out.append("Each run's figure is the median of 3 repetitions; the tables give the median over "
               "runs [IQR].")
    out.append("")
    out.append("## Prefill throughput (prompt tokens/s, max_tokens=1, prefix caching off)\n")
    out.append("| prompt length | prompts | stock (Marlin W8A16) | plugin (blockfp8 W8A8) | plugin / stock |")
    out.append("|---|---|---|---|---|")
    for i, p in enumerate(r0["prefill"]):
        s = [r["prefill"][i]["tokens_per_s"] for r in by["stock"]]
        q = [r["prefill"][i]["tokens_per_s"] for r in by["plugin"]]
        out.append(f"| {p['prompt_len']} | {p['prompts']} | {fmt(s, 0)} | {fmt(q, 0)} | "
                   f"{statistics.median(q) / statistics.median(s):.3f}x |")
    out.append("\n## Decode TPOT (ms per output token, 128-token prompts)\n")
    out.append("| batch | stock (Marlin W8A16) | plugin (blockfp8 W8A8) | stock / plugin |")
    out.append("|---|---|---|---|")
    for i, p in enumerate(r0["decode"]):
        s = [r["decode"][i]["tpot_ms"] for r in by["stock"]]
        q = [r["decode"][i]["tpot_ms"] for r in by["plugin"]]
        out.append(f"| {p['batch']} | {fmt(s, 3)} | {fmt(q, 3)} | "
                   f"{statistics.median(s) / statistics.median(q):.3f}x |")
    out.append("\n## Outputs vs the first stock run\n")
    out.append(f"{len(ref['outputs']['greedy'])} chat prompts, greedy, up to "
               f"{max(len(g['tokens']) for g in ref['outputs']['greedy'])} new tokens. "
               "Teacher-forced: logprobs of the first stock run's greedy tokens, scored by each run "
               "in one prefill (prompt_logprobs).\n")
    out.append("| run | identical sequences | tokens before first divergence | position-wise match |"
               " max abs logprob diff, greedy (up to divergence) | teacher-forced max | "
               "teacher-forced mean | teacher-forced p99 |")
    out.append("|---|---|---|---|---|---|---|---|")
    def name(r):
        return f"{r['config']} ({os.path.basename(d['files'][runs.index(r)]).split('-')[0]})"

    def rows(against, others):
        for r in others:
            c = compare(r, against)
            out.append(f"| {name(r)} | {c['identical']}/{c['prompts']} | "
                       f"{c['prefix_tokens']}/{c['ref_tokens']}"
                       f" ({100 * c['prefix_tokens'] / c['ref_tokens']:.1f}%) | "
                       f"{100 * c['pos_match'] / c['pos_total']:.1f}% | {c['lp_greedy_max']:.4f} | "
                       f"{c['lp_forced_max']:.4f} | {c['lp_forced_mean']:.5f} | "
                       f"{c['lp_forced_p99']:.4f} |")

    header = out[-2:]
    rows(ref, [r for r in runs if r is not ref])
    triton = [r for r in runs if r["config"] == "triton"]
    if triton:
        t = triton[0]
        out.append(f"\n## Outputs vs vLLM's own W8A8 path ({name(t)})\n")
        out.append(f"One run with Marlin disabled (VLLM_DISABLED_KERNELS); vLLM selected "
                   f"{', '.join(t.get('selected_from_log', [])) or '?'}. It quantizes activations "
                   "like the plugin, so it separates the effect of W8A8 from that of the kernel.\n")
        out += header
        rows(t, by["plugin"])
        out.append("\nIts own speed (one run): prefill "
                   + ", ".join(f"L={p['prompt_len']}: {p['tokens_per_s']:.0f} tok/s" for p in t["prefill"])
                   + "; TPOT " + ", ".join(f"B={p['batch']}: {p['tpot_ms']:.2f} ms" for p in t["decode"])
                   + " (vLLM's shipped default Triton config; none is tuned for this GPU).")
    out += ppl_section()
    path = os.path.join(REPO, "results", "e2e", "summary.md")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
